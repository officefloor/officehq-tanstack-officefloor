-- Settle batches: a bulk settle that settles at least one claim (one going to PENDING counts) is a batch, numbered
-- 1, 2, ... on the sheet in the order they happen (settle_batch, one row each). claim_batch is the batch that last
-- settled each claim; settling a claim one at a time takes it out of its batch. Both kept in history too (see V39 and
-- V40), so the as-of view shows them as they then were.
CREATE TABLE settle_batch (
    sheet_id     VARCHAR(255) NOT NULL,
    batch_number INT          NOT NULL,
    by_user      VARCHAR(255) NOT NULL,
    PRIMARY KEY (sheet_id, batch_number)
);
CREATE TABLE claim_batch (
    claim_id     BIGINT       NOT NULL PRIMARY KEY REFERENCES claim (id),
    sheet_id     VARCHAR(255) NOT NULL,
    batch_number INT          NOT NULL
);
CREATE INDEX claim_batch_sheet ON claim_batch (sheet_id, claim_id);

CREATE TABLE settle_batch_history AS SELECT * FROM settle_batch;
ALTER TABLE settle_batch_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE settle_batch_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE settle_batch_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX settle_batch_history_key ON settle_batch_history (sheet_id, batch_number);
CREATE TRIGGER settle_batch_journal AFTER INSERT, UPDATE, DELETE ON settle_batch FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';

CREATE TABLE claim_batch_history AS SELECT * FROM claim_batch;
ALTER TABLE claim_batch_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE claim_batch_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE claim_batch_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX claim_batch_history_key ON claim_batch_history (sheet_id, claim_id);
CREATE TRIGGER claim_batch_journal AFTER INSERT, UPDATE, DELETE ON claim_batch FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
