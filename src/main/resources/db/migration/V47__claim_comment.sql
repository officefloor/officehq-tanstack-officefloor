-- A claim's comments, oldest first (by id): the text (trimmed, never empty), the user who wrote it and the sheet's
-- today when it was written. Kept in history too (see V39 and V40), so the as-of view shows them as they then were.
CREATE TABLE claim_comment (
    id           BIGINT AUTO_INCREMENT PRIMARY KEY,
    sheet_id     VARCHAR(255)  NOT NULL,
    claim_id     BIGINT        NOT NULL REFERENCES claim (id),
    by_user      VARCHAR(255)  NOT NULL,
    commented_on DATE          NOT NULL,
    text         VARCHAR(4000) NOT NULL
);
CREATE INDEX claim_comment_sheet ON claim_comment (sheet_id, claim_id, id);
CREATE TABLE claim_comment_history AS SELECT * FROM claim_comment;
ALTER TABLE claim_comment_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE claim_comment_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE claim_comment_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX claim_comment_history_key ON claim_comment_history (sheet_id, id);
CREATE TRIGGER claim_comment_journal AFTER INSERT, UPDATE, DELETE ON claim_comment FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
