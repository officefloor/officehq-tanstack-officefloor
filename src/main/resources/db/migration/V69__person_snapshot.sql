-- The SNAPSHOTs written for a person, one row each in the order they were written: the day being left when the sheet's
-- today was changed and the person's due-total as it stood then ('n/a' when they had none). Kept in history too (see
-- V39 and V40).
CREATE TABLE person_snapshot (
    id        BIGINT AUTO_INCREMENT PRIMARY KEY,
    person_id BIGINT       NOT NULL REFERENCES person (id),
    day_left  DATE         NOT NULL,
    due_total VARCHAR(40)  NOT NULL
);
CREATE INDEX person_snapshot_person ON person_snapshot (person_id, id);
CREATE TABLE person_snapshot_history AS SELECT * FROM person_snapshot;
ALTER TABLE person_snapshot_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE person_snapshot_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE person_snapshot_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX person_snapshot_history_key ON person_snapshot_history (person_id, id);
CREATE TRIGGER person_snapshot_journal AFTER INSERT, UPDATE, DELETE ON person_snapshot FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
