-- The sheet's pools: a name (trimmed, unique on the sheet) and its members.
CREATE TABLE pool (
    id        BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id  VARCHAR(200)  NOT NULL REFERENCES sheet (id),
    name      VARCHAR(200)  NOT NULL,
    added_by  VARCHAR(200)  NOT NULL,
    CONSTRAINT pool_unique UNIQUE (sheet_id, name)
);
-- A pool's members: a person of the sheet (at most once in a pool) and their share percent. A retired
-- member's share counts as 0.00 toward the pool's total.
CREATE TABLE pool_member (
    id        BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id  VARCHAR(200)  NOT NULL REFERENCES sheet (id),
    pool_id   BIGINT        NOT NULL REFERENCES pool (id),
    person_id BIGINT        NOT NULL REFERENCES person (id),
    share     DECIMAL(5,2)  NOT NULL,
    added_by  VARCHAR(200)  NOT NULL,
    CONSTRAINT pool_member_unique UNIQUE (pool_id, person_id)
);
