-- The policy settings (rounding, floor, cap, terms, late-pct, clerk-limit) are versioned together: every save of one of
-- them is a new version of the sheet's policy, numbered from 1 in the order made, with the from-date it was saved from
-- (null: none, so it counts on every date). A claim is under the number of versions whose from-date is on or before its date.
-- Values saved before versions were kept are a version each, in from-date order; one from the beginning of time has no from-date.
-- Kept in history too (see V39).
CREATE TABLE policy_version (
    sheet_id    VARCHAR(255) NOT NULL,
    version_no  INTEGER      NOT NULL,
    setting_key VARCHAR(64)  NOT NULL,
    from_date   DATE,
    PRIMARY KEY (sheet_id, version_no)
);
INSERT INTO policy_version (sheet_id, version_no, setting_key, from_date)
    SELECT sheet_id, ROW_NUMBER() OVER (PARTITION BY sheet_id ORDER BY from_date, setting_key), setting_key,
           CASE WHEN from_date = DATE '0001-01-01' THEN NULL ELSE from_date END
    FROM setting_from WHERE setting_key IN ('rounding', 'floor', 'cap', 'terms', 'late-pct', 'clerk-limit');
CREATE TABLE policy_version_history AS SELECT * FROM policy_version;
ALTER TABLE policy_version_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE policy_version_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE policy_version_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX policy_version_history_key ON policy_version_history (sheet_id, version_no);
CREATE TRIGGER policy_version_journal AFTER INSERT, UPDATE, DELETE ON policy_version FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
