-- The sheet's void reasons, listed in the order they were added; each reason at most once per sheet, without regard to
-- case. While a sheet has any, a claim is voided only with one of them, kept on the claim (null: voided without one, or
-- not voided). Kept in history too (see V39 and V40); the claim's journal trigger is made again around the change, as
-- in V41.
CREATE TABLE void_reason (
    sheet_id VARCHAR(255) NOT NULL,
    reason VARCHAR(255) NOT NULL,
    listed BIGINT NOT NULL,
    PRIMARY KEY (sheet_id, reason)
);
CREATE TABLE void_reason_history AS SELECT * FROM void_reason;
ALTER TABLE void_reason_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE void_reason_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE void_reason_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX void_reason_history_key ON void_reason_history (sheet_id, reason);
CREATE TRIGGER void_reason_journal AFTER INSERT, UPDATE, DELETE ON void_reason FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
DROP TRIGGER claim_journal;
ALTER TABLE claim ADD COLUMN void_reason VARCHAR(255);
ALTER TABLE claim_history ADD COLUMN void_reason VARCHAR(255);
CREATE TRIGGER claim_journal AFTER INSERT, UPDATE, DELETE ON claim FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
