-- The history of the rows a person's figures are worked out from: every row a change writes to claim, person,
-- person_grade, person_hold, rate, setting or setting_from is copied to <table>_history (by the Journal trigger) with
-- the sheet's today when the change was made (history_on), in the order made (history_seq); a deleted row is copied
-- as it was, marked history_gone. A statement taken as of a date reads these tables back: each row as its last copy
-- made on or before that date left it. A column added to one of these tables must be added to its history too.
-- Rows stored before the history was kept were made at the beginning of time.
CREATE TABLE claim_history AS SELECT * FROM claim;
CREATE TABLE person_history AS SELECT * FROM person;
CREATE TABLE person_grade_history AS SELECT * FROM person_grade;
CREATE TABLE person_hold_history AS SELECT * FROM person_hold;
CREATE TABLE rate_history AS SELECT * FROM rate;
CREATE TABLE setting_history AS SELECT * FROM setting;
CREATE TABLE setting_from_history AS SELECT * FROM setting_from;

ALTER TABLE claim_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE claim_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE claim_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE person_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE person_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE person_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE person_grade_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE person_grade_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE person_grade_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE person_hold_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE person_hold_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE person_hold_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE rate_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE rate_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE rate_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE setting_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE setting_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE setting_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE setting_from_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE setting_from_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE setting_from_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;

CREATE INDEX claim_history_key ON claim_history (sheet_id, id);
CREATE INDEX person_history_key ON person_history (sheet_id, id);
CREATE INDEX person_grade_history_key ON person_grade_history (person_id, from_date);
CREATE INDEX person_hold_history_key ON person_hold_history (person_id, id);
CREATE INDEX rate_history_key ON rate_history (sheet_id, grade);
CREATE INDEX setting_history_key ON setting_history (sheet_id, setting_key);
CREATE INDEX setting_from_history_key ON setting_from_history (sheet_id, setting_key);

CREATE TRIGGER claim_journal AFTER INSERT, UPDATE, DELETE ON claim FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
CREATE TRIGGER person_journal AFTER INSERT, UPDATE, DELETE ON person FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
CREATE TRIGGER person_grade_journal AFTER INSERT, UPDATE, DELETE ON person_grade FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
CREATE TRIGGER person_hold_journal AFTER INSERT, UPDATE, DELETE ON person_hold FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
CREATE TRIGGER rate_journal AFTER INSERT, UPDATE, DELETE ON rate FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
CREATE TRIGGER setting_journal AFTER INSERT, UPDATE, DELETE ON setting FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
CREATE TRIGGER setting_from_journal AFTER INSERT, UPDATE, DELETE ON setting_from FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
