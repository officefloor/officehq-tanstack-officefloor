-- Each year end rollover made on a sheet: the old fiscal year's name, who made it and on which of the sheet's todays,
-- the periods it generated and the opening balances it set (each amount it added to a person's opening for a period).
-- Only the sheet's last rollover can be undone (once): undone marks it so.
CREATE TABLE rollover (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id VARCHAR(255) NOT NULL,
    fy VARCHAR(16) NOT NULL,
    made_by VARCHAR(255) NOT NULL,
    made_on DATE NOT NULL,
    undone BOOLEAN DEFAULT FALSE NOT NULL
);
CREATE INDEX rollover_sheet ON rollover (sheet_id);
CREATE TABLE rollover_period (
    rollover_id BIGINT NOT NULL,
    period_name VARCHAR(255) NOT NULL,
    PRIMARY KEY (rollover_id, period_name)
);
CREATE TABLE rollover_opening (
    rollover_id BIGINT NOT NULL,
    period_name VARCHAR(255) NOT NULL,
    person_id BIGINT NOT NULL,
    amount DECIMAL(15, 2) NOT NULL,
    PRIMARY KEY (rollover_id, period_name, person_id)
);
