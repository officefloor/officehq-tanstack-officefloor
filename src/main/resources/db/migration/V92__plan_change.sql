-- A plan's amount changes, in the order they were made: the sheet's today when changed and the new amount.
-- The plan's own amount is the latest; claims already made keep the amount they were made with.
CREATE TABLE plan_change (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id    BIGINT        NOT NULL REFERENCES plan (id),
    changed_on DATE          NOT NULL,
    amount     DECIMAL(19,2) NOT NULL
);
