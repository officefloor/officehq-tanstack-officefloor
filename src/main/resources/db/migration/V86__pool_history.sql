-- Pools and crews (a crew is also a pool) kept in history too (see V39 and V40), so a pool member's cut can be
-- figured as it stood at the end of a period: the pool, its members and the pot as they were then.
CREATE TABLE pool_history AS SELECT * FROM pool;
ALTER TABLE pool_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE pool_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE pool_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE TABLE pool_member_history AS SELECT * FROM pool_member;
ALTER TABLE pool_member_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE pool_member_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE pool_member_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE TABLE pool_nested_history AS SELECT * FROM pool_nested;
ALTER TABLE pool_nested_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE pool_nested_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE pool_nested_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE TABLE crew_history AS SELECT * FROM crew;
ALTER TABLE crew_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE crew_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE crew_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE TABLE crew_member_history AS SELECT * FROM crew_member;
ALTER TABLE crew_member_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE crew_member_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE crew_member_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX pool_history_key ON pool_history (sheet_id, name);
CREATE INDEX pool_member_history_key ON pool_member_history (sheet_id, pool_name, person_id);
CREATE INDEX pool_nested_history_key ON pool_nested_history (sheet_id, member_pool);
CREATE INDEX crew_history_key ON crew_history (sheet_id, name);
CREATE INDEX crew_member_history_key ON crew_member_history (sheet_id, crew_name, person_id);
CREATE TRIGGER pool_journal AFTER INSERT, UPDATE, DELETE ON pool FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
CREATE TRIGGER pool_member_journal AFTER INSERT, UPDATE, DELETE ON pool_member FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
CREATE TRIGGER pool_nested_journal AFTER INSERT, UPDATE, DELETE ON pool_nested FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
CREATE TRIGGER crew_journal AFTER INSERT, UPDATE, DELETE ON crew FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
CREATE TRIGGER crew_member_journal AFTER INSERT, UPDATE, DELETE ON crew_member FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
