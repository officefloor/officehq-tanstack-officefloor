-- A plan's pauses: the day it was paused and the day it was resumed (NULL while still paused). A plan
-- date on or after paused_on and before resumed_on is skipped, not postponed.
CREATE TABLE plan_pause (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id    BIGINT NOT NULL REFERENCES plan (id),
    paused_on  DATE   NOT NULL,
    resumed_on DATE
);
