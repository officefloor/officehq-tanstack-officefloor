-- A DRAFT claim's lines, in the order added (by id): a label (trimmed, never empty), a quantity (a whole number, at
-- least 1) and a unit amount (two decimals). A claim with lines has as its amount the quantities times the unit amounts
-- added up. Kept in history too (see V39 and V40), so the as-of view shows them as they then were.
CREATE TABLE claim_line (
    id       BIGINT AUTO_INCREMENT PRIMARY KEY,
    sheet_id VARCHAR(255)   NOT NULL,
    claim_id BIGINT         NOT NULL REFERENCES claim (id),
    label    VARCHAR(4000)  NOT NULL,
    qty      INT            NOT NULL,
    unit     DECIMAL(19, 2) NOT NULL
);
CREATE INDEX claim_line_sheet ON claim_line (sheet_id, claim_id, id);
CREATE TABLE claim_line_history AS SELECT * FROM claim_line;
ALTER TABLE claim_line_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE claim_line_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE claim_line_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX claim_line_history_key ON claim_line_history (sheet_id, id);
CREATE TRIGGER claim_line_journal AFTER INSERT, UPDATE, DELETE ON claim_line FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
