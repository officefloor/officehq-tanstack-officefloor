-- The sheet's notes: each a text, the user who added it and the sheet's today when it was added. Listed newest first;
-- read as of a date, only those added while the sheet's today was on or before it.
CREATE TABLE sheet_note (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id VARCHAR(255) NOT NULL,
    added_on DATE         NOT NULL,
    added_by VARCHAR(255) NOT NULL,
    text     VARCHAR(4000) NOT NULL
);
CREATE INDEX sheet_note_sheet ON sheet_note (sheet_id);
