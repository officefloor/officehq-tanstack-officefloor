-- A person's own terms are dated: person.terms are the terms recorded from the beginning of time; each row here are
-- terms recorded from a date on (terms null: none of their own from then). At most one per date.
-- Kept in history too (see V39 and V40).
CREATE TABLE person_terms (
    person_id BIGINT  NOT NULL,
    from_date DATE    NOT NULL,
    terms     INTEGER,
    PRIMARY KEY (person_id, from_date)
);
CREATE TABLE person_terms_history AS SELECT * FROM person_terms;
ALTER TABLE person_terms_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE person_terms_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE person_terms_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX person_terms_history_key ON person_terms_history (person_id, from_date);
CREATE TRIGGER person_terms_journal AFTER INSERT, UPDATE, DELETE ON person_terms FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
