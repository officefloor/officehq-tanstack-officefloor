-- A person's past retirements: each from the date they were retired from to the day they were unretired. A claim
-- dated after the from-date and before the to-date of one is refused, as one after a current retirement is.
-- Kept in history too (see V39 and V40).
CREATE TABLE person_retirement (
    id        BIGINT AUTO_INCREMENT PRIMARY KEY,
    person_id BIGINT NOT NULL REFERENCES person (id),
    from_date DATE   NOT NULL,
    to_date   DATE   NOT NULL
);
CREATE INDEX person_retirement_person ON person_retirement (person_id, from_date);
CREATE TABLE person_retirement_history AS SELECT * FROM person_retirement;
ALTER TABLE person_retirement_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE person_retirement_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE person_retirement_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX person_retirement_history_key ON person_retirement_history (person_id, id);
CREATE TRIGGER person_retirement_journal AFTER INSERT, UPDATE, DELETE ON person_retirement FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
