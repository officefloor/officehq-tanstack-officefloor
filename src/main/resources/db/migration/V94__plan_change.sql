-- A plan's amount changes, in the order made: on the sheet's today, the new amount (also kept on the plan itself, so
-- the claims generated from then on use it; claims already generated keep theirs).
CREATE TABLE plan_change (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id    BIGINT        NOT NULL,
    changed_on DATE          NOT NULL,
    amount     DECIMAL(19, 2) NOT NULL
);
