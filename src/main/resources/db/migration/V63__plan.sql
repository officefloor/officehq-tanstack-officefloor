-- A person's plans: an amount (as the claim form keeps it), a start date, every N days (N >= 1) and an
-- end date (not before the start). Generating makes a DRAFT claim for each plan date up to the end and
-- the sheet's today that has none yet; plan_claim keeps the dates each plan has made a claim for.
CREATE TABLE plan (
    id          BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id    VARCHAR(200)  NOT NULL REFERENCES sheet (id),
    person_id   BIGINT        NOT NULL REFERENCES person (id),
    amount      DECIMAL(19,2) NOT NULL,
    start_date  DATE          NOT NULL,
    every_days  INT           NOT NULL,
    end_date    DATE          NOT NULL,
    added_by    VARCHAR(200)  NOT NULL
);

CREATE TABLE plan_claim (
    plan_id    BIGINT NOT NULL REFERENCES plan (id),
    claim_date DATE   NOT NULL,
    claim_id   BIGINT NOT NULL REFERENCES claim (id),
    CONSTRAINT plan_claim_unique UNIQUE (plan_id, claim_date)
);
