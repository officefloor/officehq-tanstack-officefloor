-- A person's plans, in the order added: an amount, a start date, every N days (at least 1) and an end date. Each
-- plan date a claim was generated for is kept, with that claim, so a date is made at most once.
CREATE TABLE plan (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet      VARCHAR(200)   NOT NULL,
    person_id  BIGINT         NOT NULL,
    amount     DECIMAL(19, 2) NOT NULL,
    start_date DATE           NOT NULL,
    every_days INT            NOT NULL,
    end_date   DATE           NOT NULL
);
CREATE TABLE plan_claim (
    plan_id  BIGINT NOT NULL,
    plan_day DATE   NOT NULL,
    claim_id BIGINT NOT NULL,
    PRIMARY KEY (plan_id, plan_day)
);
