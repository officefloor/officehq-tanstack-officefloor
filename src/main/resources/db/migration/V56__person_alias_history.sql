CREATE TABLE person_alias_history AS SELECT * FROM person_alias;
ALTER TABLE person_alias_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE person_alias_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE person_alias_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
