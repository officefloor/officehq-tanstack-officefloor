-- A claim's shares, in the order added (by id): another person on the sheet holding a part of its due, as a percent
-- (two decimals, more than 0.00; a claim's shares add up to no more than 100.00). Kept in history too (see V39 and
-- V40), so the as-of view shows them as they then were.
CREATE TABLE claim_share (
    id        BIGINT AUTO_INCREMENT PRIMARY KEY,
    sheet_id  VARCHAR(255)  NOT NULL,
    claim_id  BIGINT        NOT NULL REFERENCES claim (id),
    person_id BIGINT        NOT NULL,
    share     DECIMAL(5, 2) NOT NULL
);
CREATE INDEX claim_share_sheet ON claim_share (sheet_id, claim_id, id);
CREATE TABLE claim_share_history AS SELECT * FROM claim_share;
ALTER TABLE claim_share_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE claim_share_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE claim_share_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX claim_share_history_key ON claim_share_history (sheet_id, id);
CREATE TRIGGER claim_share_journal AFTER INSERT, UPDATE, DELETE ON claim_share FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
