-- The sheet's claim templates: a name (trimmed, unique on the sheet), an amount (as the claim form keeps it)
-- and a note. A claim made from one copies its amount and note at that moment.
CREATE TABLE claim_template (
    id        BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id  VARCHAR(200)  NOT NULL REFERENCES sheet (id),
    name      VARCHAR(200)  NOT NULL,
    amount    DECIMAL(19,2) NOT NULL,
    note      VARCHAR(2000) NOT NULL,
    saved_by  VARCHAR(200)  NOT NULL,
    CONSTRAINT claim_template_unique UNIQUE (sheet_id, name)
);
