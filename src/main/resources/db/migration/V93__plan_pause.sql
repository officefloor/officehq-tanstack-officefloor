-- A plan's pauses, in the order made: paused on a day, and resumed on a later one (null while still paused). A plan
-- date on or after the day paused and before the day resumed is skipped.
CREATE TABLE plan_pause (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id    BIGINT NOT NULL,
    paused_on  DATE   NOT NULL,
    resumed_on DATE
);
