-- The grades added on a sheet beyond A, B and C, in the order they were added: a code of one to three capital letters.
CREATE TABLE grade (
    sheet_id VARCHAR(255) NOT NULL,
    grade    VARCHAR(3)   NOT NULL,
    seq      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    PRIMARY KEY (sheet_id, grade)
);

-- A grade may now be up to three letters wherever one is kept.
