-- The sheet's crews: a name (trimmed, unique on the sheet) and a lead, a person of the sheet.
CREATE TABLE crew (
    id        BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id  VARCHAR(200)  NOT NULL REFERENCES sheet (id),
    name      VARCHAR(200)  NOT NULL,
    lead_id   BIGINT        NOT NULL REFERENCES person (id),
    added_by  VARCHAR(200)  NOT NULL,
    CONSTRAINT crew_unique UNIQUE (sheet_id, name)
);
-- A crew's members: people of the sheet, each at most once in a crew and never its lead.
CREATE TABLE crew_member (
    id        BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id  VARCHAR(200)  NOT NULL REFERENCES sheet (id),
    crew_id   BIGINT        NOT NULL REFERENCES crew (id),
    person_id BIGINT        NOT NULL REFERENCES person (id),
    added_by  VARCHAR(200)  NOT NULL,
    CONSTRAINT crew_member_unique UNIQUE (crew_id, person_id)
);
