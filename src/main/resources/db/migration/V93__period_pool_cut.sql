-- Closing or soft-closing a period fixes each pool member's cut for it as it stands at that moment: one row per member
-- of each pool (and crew) then, its cut as shown ('' when it had none). Closing again fixes them afresh; reopening drops
-- them, so the period's cut is live again. A member is named by its pool's name and pool:<name> for a pool, or the
-- person's id. Kept in history too (see V39 and V40).
CREATE TABLE period_pool_cut (
    sheet_id    VARCHAR(255) NOT NULL,
    period_name VARCHAR(255) NOT NULL,
    pool_name   VARCHAR(255) NOT NULL,
    member      VARCHAR(255) NOT NULL,
    cut         VARCHAR(32)  NOT NULL,
    PRIMARY KEY (sheet_id, period_name, pool_name, member)
);
CREATE TABLE period_pool_cut_history AS SELECT * FROM period_pool_cut;
ALTER TABLE period_pool_cut_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE period_pool_cut_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE period_pool_cut_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX period_pool_cut_history_key ON period_pool_cut_history (sheet_id, period_name, pool_name, member);
CREATE TRIGGER period_pool_cut_journal AFTER INSERT, UPDATE, DELETE ON period_pool_cut FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
