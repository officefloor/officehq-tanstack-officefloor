-- Each person's opening balance for a period, pasted as name,period,amount: every paste line adds its amount (two
-- decimals, 0.00 or more) to the row, which is added to the person's carried figure for the period. Closing or
-- soft-closing the period fixes the carried figure with it. Kept in history too (see V39 and V40).
CREATE TABLE period_person_opening (
    sheet_id VARCHAR(255) NOT NULL,
    period_name VARCHAR(255) NOT NULL,
    person_id BIGINT NOT NULL,
    amount DECIMAL(15, 2) NOT NULL,
    PRIMARY KEY (sheet_id, period_name, person_id)
);
CREATE TABLE period_person_opening_history AS SELECT * FROM period_person_opening;
ALTER TABLE period_person_opening_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE period_person_opening_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE period_person_opening_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX period_person_opening_history_key ON period_person_opening_history (sheet_id, period_name, person_id);
CREATE TRIGGER period_person_opening_journal AFTER INSERT, UPDATE, DELETE ON period_person_opening FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
