-- The sheet's holidays: a claim's due-by, fixed when it is made, that falls on one is moved to the next day that is not
-- a holiday. Each date at most once per sheet. Kept in history too (see V39 and V40).
CREATE TABLE holiday (
    sheet_id VARCHAR(255) NOT NULL,
    holiday_date DATE NOT NULL,
    PRIMARY KEY (sheet_id, holiday_date)
);
CREATE TABLE holiday_history AS SELECT * FROM holiday;
ALTER TABLE holiday_history ADD COLUMN history_on DATE DEFAULT DATE '0001-01-01' NOT NULL;
ALTER TABLE holiday_history ADD COLUMN history_gone BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE holiday_history ADD COLUMN history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX holiday_history_key ON holiday_history (sheet_id, holiday_date);
CREATE TRIGGER holiday_journal AFTER INSERT, UPDATE, DELETE ON holiday FOR EACH ROW CALL 'net.officefloor.hq.app.history.Journal';
