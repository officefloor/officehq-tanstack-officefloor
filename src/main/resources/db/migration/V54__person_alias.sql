-- A person's aliases (stored trimmed). An alias is compared as names are, without regard to case,
-- and shares the names' uniqueness on the sheet: no alias equals another, nor any person's name.
CREATE TABLE person_alias (
    id        BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id  VARCHAR(200) NOT NULL REFERENCES sheet (id),
    person_id BIGINT       NOT NULL REFERENCES person (id),
    alias     VARCHAR(200) NOT NULL,
    alias_key VARCHAR(200) GENERATED ALWAYS AS (LOWER(alias)),
    added_by  VARCHAR(200) NOT NULL
);
CREATE UNIQUE INDEX person_alias_sheet_key ON person_alias (sheet_id, alias_key);
