-- Each merge of one person into another, so the last merge into a person can be undone on the
-- sheet's today it was made, by the one who made it. A merge made as a person arrives by transfer is
-- kept too (it is the last merge into that person) but cannot be undone (undoable false).
CREATE TABLE person_merge (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id   VARCHAR(200) NOT NULL REFERENCES sheet (id),
    from_id    BIGINT       NOT NULL,
    from_name  VARCHAR(200) NOT NULL,
    into_id    BIGINT       NOT NULL,
    merged_by  VARCHAR(200) NOT NULL,
    merged_on  DATE         NOT NULL,
    undoable   BOOLEAN      NOT NULL,
    undone     BOOLEAN      DEFAULT FALSE NOT NULL,
    -- The alias the merged person's name became on the other.
    name_alias_id BIGINT
);
CREATE INDEX person_merge_into ON person_merge (sheet_id, into_id, id);

-- What a merge moved to the other or dropped, to give back on an undo: the claims that came from the
-- merged person (kind CLAIM, ref the claim id), their own aliases (kind ALIAS, ref the alias id).
CREATE TABLE person_merge_moved (
    merge_id BIGINT      NOT NULL REFERENCES person_merge (id),
    kind     VARCHAR(20) NOT NULL,
    ref      BIGINT      NOT NULL
);
CREATE INDEX person_merge_moved_merge ON person_merge_moved (merge_id);

-- The merged person's own rows (the person and their grades, terms, histories, holds and watches) as
-- they stood when merged away: one value per column, by table and row.
CREATE TABLE person_merge_value (
    merge_id BIGINT       NOT NULL REFERENCES person_merge (id),
    tbl      VARCHAR(100) NOT NULL,
    row_no   INT          NOT NULL,
    col      VARCHAR(100) NOT NULL,
    val      VARCHAR(10000)
);
CREATE INDEX person_merge_value_merge ON person_merge_value (merge_id);
