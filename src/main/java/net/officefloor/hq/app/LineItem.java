package net.officefloor.hq.app;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.Transient;
import java.math.BigDecimal;

/**
 * One line on an invoice: what is being charged for (a description), how many (qty) and the price of
 * each (unit price), plus the id of the {@link Invoice} it belongs to. The line's own amount is
 * qty * unit price, and the invoice's amount is the sum across its lines. Mapped to the
 * {@code line_item} table created by {@code V15__line_items.sql}. IDENTITY id so the DB assigns it on
 * insert (seed inserts explicit ids via JdbcTemplate; GENERATED BY DEFAULT allows both).
 */
@Entity
@Table(name = "line_item")
public class LineItem {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "invoice_id")
    private Long invoiceId;

    private String description;

    private Integer qty;

    private String unit;

    @Column(name = "unit_price")
    private BigDecimal unitPrice;

    /**
     * The currency this line's money is shown in — the billing currency of the client the line's
     * invoice belongs to (an ISO code, {@code USD} or {@code EUR}). Derived, not stored
     * ({@code @Transient} keeps it out of the {@code line_item} table); {@link LineItemsGet} fills it
     * by joining the line's invoice back to its project's client, so the invoice-detail line amounts
     * read in the same currency as the rest of the invoice.
     */
    @Transient
    private String currency;

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Long getInvoiceId() {
        return invoiceId;
    }

    public void setInvoiceId(Long invoiceId) {
        this.invoiceId = invoiceId;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public Integer getQty() {
        return qty;
    }

    public void setQty(Integer qty) {
        this.qty = qty;
    }

    public String getUnit() {
        return unit;
    }

    public void setUnit(String unit) {
        this.unit = unit;
    }

    public BigDecimal getUnitPrice() {
        return unitPrice;
    }

    public void setUnitPrice(BigDecimal unitPrice) {
        this.unitPrice = unitPrice;
    }

    public String getCurrency() {
        return currency;
    }

    public void setCurrency(String currency) {
        this.currency = currency;
    }
}
