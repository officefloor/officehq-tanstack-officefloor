package net.officefloor.hq.app;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.Transient;
import java.math.BigDecimal;

/**
 * An invoice raised against a project: the id of the {@link Project} it belongs to and a money
 * amount. Mapped to the {@code invoice} table created by {@code V4__invoices.sql}. IDENTITY id so
 * the DB assigns it on insert (seed inserts explicit ids via JdbcTemplate; GENERATED BY DEFAULT
 * allows both).
 */
@Entity
@Table(name = "invoice")
public class Invoice {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "project_id")
    private Long projectId;

    private BigDecimal amount;

    /**
     * Lifecycle status: DRAFT by default, SENT once sent, PAID once paid (see V5__invoice_status.sql
     * and V11__invoice_draft_default.sql).
     */
    private String status;

    /** The day the invoice went out, an ISO date literal (see V9__invoice_dates.sql). */
    @Column(name = "issued_date")
    private String issuedDate;

    /** The day the invoice is due, an ISO date literal (see V9__invoice_dates.sql). */
    @Column(name = "due_date")
    private String dueDate;

    /**
     * How much is still owed on this invoice: its {@link #amount} minus every payment recorded
     * against it. Derived, not stored — {@code @Transient} keeps it out of the {@code invoice}
     * table; {@link InvoicesGet} fills it from the payments before sending the list so the project
     * invoices view can show the amount still due after payments.
     */
    @Transient
    private BigDecimal amountDue;

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Long getProjectId() {
        return projectId;
    }

    public void setProjectId(Long projectId) {
        this.projectId = projectId;
    }

    public BigDecimal getAmount() {
        return amount;
    }

    public void setAmount(BigDecimal amount) {
        this.amount = amount;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getIssuedDate() {
        return issuedDate;
    }

    public void setIssuedDate(String issuedDate) {
        this.issuedDate = issuedDate;
    }

    public String getDueDate() {
        return dueDate;
    }

    public void setDueDate(String dueDate) {
        this.dueDate = dueDate;
    }

    public BigDecimal getAmountDue() {
        return amountDue;
    }

    public void setAmountDue(BigDecimal amountDue) {
        this.amountDue = amountDue;
    }
}
